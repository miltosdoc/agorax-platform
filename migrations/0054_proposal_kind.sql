-- 0054_proposal_kind
--
-- Τι είδους ψηφοφορία είναι μια πρόταση.
--
-- Οι κοινότητες δεν ψηφίζουν μόνο «αποφάσεις». Ψηφίζουν το καταστατικό τους,
-- εκλέγουν πρόσωπα σε θέσεις, και θέλουν να ρωτήσουν τα μέλη τη γνώμη τους
-- χωρίς να δεσμευτούν. Μέχρι τώρα όλα αυτά ήταν «πρόταση» και ο αναγνώστης
-- έπρεπε να μαντέψει από τον τίτλο τι ψηφίζει.
--
--   decision — απόφαση: η κοινότητα εγκρίνει ή απορρίπτει (ή διαλέγει επιλογή)
--   statute  — καταστατικό ή κανονισμός: έγκριση ή τροποποίηση
--   election — εκλογή: τα μέλη διαλέγουν ανάμεσα σε υποψηφίους
--   poll     — δημοσκόπηση της κοινότητας: καταγράφει γνώμη, δεν αποφασίζει
--
-- Default 'decision': κάθε υπάρχουσα πρόταση ήταν ακριβώς αυτό, οπότε τίποτα
-- δεν αλλάζει όψη. Οι δημοσκοπήσεις της πλατφόρμας (survey_polls) δεν
-- αγγίζονται — αυτή είναι η απλή, εσωτερική δημοσκόπηση μιας κοινότητας.

ALTER TABLE proposals
  ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'decision';

COMMENT ON COLUMN proposals.kind IS
  'What the vote is: decision | statute | election | poll. A poll records opinion and decides nothing.';
