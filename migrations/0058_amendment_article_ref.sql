-- 0058_amendment_article_ref
--
-- Ένα καταστατικό τροποποιείται άρθρο προς άρθρο: κάθε τροπολογία λέει σε
-- ποιο άρθρο αναφέρεται, και η συγχώνευση με AI ξαναγράφει μόνο εκείνο το
-- άρθρο. Τα υπόλοιπα φτάνουν στην κάλπη ακριβώς όπως γράφτηκαν.
--
-- article_ref: ο αριθμός του άρθρου όπως είναι γραμμένος ('5', '5Α'),
-- 'preamble' για το κείμενο πριν από το πρώτο άρθρο, ή 'new' για νέο άρθρο.
-- NULL σε κάθε άλλο κείμενο και στις τροπολογίες που υποβλήθηκαν πριν από
-- αυτή την αλλαγή· αυτές συγχωνεύονται σε όλο το κείμενο, όπως πάντα.
--
-- Μόνο προσθήκη στήλης, οπότε τρέχει με ασφάλεια και δεύτερη φορά.

ALTER TABLE "proposal_amendments" ADD COLUMN IF NOT EXISTS "article_ref" text;
