-- 0057_agora_consent
--
-- Η πλατφόρμα λέγεται πλέον Αγορά (Agora). Το κείμενο συναίνεσης την
-- ονομάζει, οπότε άλλαξε, και μαζί του η έκδοσή του
-- (shared/consent.ts, CURRENT_CONSENT_VERSION = 2026-09-30.1).
--
-- Τίποτα άλλο δεν ξαναρωτά τα μέλη όταν αλλάζει η έκδοση: η οθόνη
-- αποδοχής εμφανίζεται μόνο όταν users.requires_consent είναι true. Εδώ
-- ξαναγίνεται true για όποιον δεν έχει αποδεχτεί ακόμη τη νέα έκδοση,
-- ώστε στην επόμενη επίσκεψή του να δει το νέο κείμενο και να το
-- αποδεχτεί. Όποιος την αποδέχτηκε ήδη (π.χ. γράφτηκε μετά την
-- ενημέρωση του κώδικα) δεν ξαναρωτιέται, οπότε η σειρά ανάμεσα σε
-- migration και deploy δεν έχει σημασία, και το αρχείο τρέχει με
-- ασφάλεια και δεύτερη φορά.
--
-- Η συναίνεση του πάνελ δημοσκοπήσεων (shared/polling.ts) άλλαξε κι αυτή,
-- αλλά ελέγχεται μόνο όταν κάποιος μπαίνει στο πάνελ· τα σημερινά μέλη
-- του πάνελ κρατούν την αποδοχή που έδωσαν.

UPDATE "users" SET "requires_consent" = true
WHERE "requires_consent" = false
  AND NOT EXISTS (
    SELECT 1 FROM "user_consents" c
    WHERE c."user_id" = "users"."id"
      AND c."consent_version" = '2026-09-30.1'
      AND c."withdrawn_at" IS NULL
  );
