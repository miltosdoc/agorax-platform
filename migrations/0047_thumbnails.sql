-- 0047_thumbnails
--
-- Μια εικόνα για κάθε κοινότητα, πρόταση και δημοσκόπηση.
--
-- Η νέα σχεδίαση έχει θέση εικόνας σε κάθε κάρτα. Χωρίς αυτή τη στήλη κάθε
-- τέτοια θέση είναι ένα γκρι κουτί, που δεν διαβάζεται ως «κενό» αλλά ως
-- «χαλασμένο».
--
-- Το περιεχόμενο ΔΕΝ είναι διαδρομή αρχείου: είναι κλειδί καταλόγου της μορφής
-- `<μοτίβο>-<παλέτα>` (shared/thumbnails.ts) που σχεδιάζεται ως SVG στον
-- browser. Γι' αυτό δεν υπάρχει FK, δεν υπάρχει αποθήκευση αρχείου και δεν
-- χρειάζεται μετακίνηση δεδομένων.
--
-- NULL σημαίνει «δεν διάλεξε κανείς»: τότε το κλειδί παράγεται ντετερμινιστικά
-- από το id της γραμμής, ώστε η ίδια γραμμή να δείχνει πάντα την ίδια εικόνα.
-- Δεν κάνουμε backfill — μια αποθηκευμένη τιμή θα ήταν ψεύτικη επιλογή
-- συντάκτη, και θα εμπόδιζε την αλλαγή του καταλόγου αργότερα.
--
-- Η ανεβασμένη φωτογραφία (communities.cover_path / avatar_path) υπερισχύει
-- πάντα· αυτό είναι το γέμισμα μέχρι να υπάρξει.

ALTER TABLE communities  ADD COLUMN IF NOT EXISTS thumbnail_key TEXT;
ALTER TABLE proposals    ADD COLUMN IF NOT EXISTS thumbnail_key TEXT;
ALTER TABLE survey_polls ADD COLUMN IF NOT EXISTS thumbnail_key TEXT;
