-- 0059_article_ballot
--
-- Ψηφοφορία «κατ' άρθρο και στο σύνολο» για το καταστατικό.
--
-- proposals.article_ballot: το ψηφοδέλτιο ενός καταστατικού που ψηφίζεται
-- άρθρο προς άρθρο — ένα ερώτημα για το σύνολο, ένα για κάθε άρθρο, με
-- εκδοχές Α/Β όπου η συνδιαμόρφωση έβγαλε αντιπρόταση (shared/article-ballot.ts).
-- Παγώνει όταν ανοίγει η ψηφοφορία· NULL σε κάθε άλλη ψηφοφορία. Οι ψήφοι
-- μένουν στον ίδιο πίνακα και με τον ίδιο ανώνυμο μηχανισμό: όλες οι
-- απαντήσεις ενός ψηφοφόρου πάνε σε μία ψήφο.
--
-- communities.constitution_scope: τι συγκεντρώνει το Σύνταγμα της κοινότητας
-- από τις ψηφοφορίες της — 'all' (ό,τι αποφασίστηκε: καταστατικό, αποφάσεις,
-- εκλογές, όπως μέχρι τώρα), 'statute_decisions', 'statute' ή 'decisions'.
-- Αλλάζει όπως οι άλλοι κανόνες: με ψηφοφορία των μελών στις αυτόνομες
-- κοινότητες.
--
-- Μόνο προσθήκη στηλών, οπότε τρέχει με ασφάλεια και δεύτερη φορά.

ALTER TABLE "proposals" ADD COLUMN IF NOT EXISTS "article_ballot" jsonb;
ALTER TABLE "communities" ADD COLUMN IF NOT EXISTS "constitution_scope" text NOT NULL DEFAULT 'all';
