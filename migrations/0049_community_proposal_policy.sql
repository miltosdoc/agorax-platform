-- 0049_community_proposal_policy
--
-- Ποιος μπορεί να καταθέσει πρόταση σε μια κοινότητα.
--
-- Μέχρι τώρα η ιδιότητα του μέλους ήταν η μόνη προϋπόθεση: όποιος ανήκε στην
-- κοινότητα μπορούσε να καταθέσει. Σε μια διαχειριζόμενη κοινότητα αυτό δεν
-- ήταν πάντα το ζητούμενο — ο ιδρυτής χρειάζεται να μπορεί να κρατήσει την
-- κατάθεση προτάσεων στην ομάδα διαχείρισης.
--
--   all_members — κάθε μέλος (η μόνη τιμή για τις αυτόνομες κοινότητες)
--   admins      — ιδρυτής και διαχειριστές
--   founder     — μόνο ο ιδρυτής
--
-- Default 'all_members': κάθε υπάρχουσα κοινότητα συνεχίζει ακριβώς όπως
-- λειτουργούσε χθες. Ο περιορισμός είναι ρητή επιλογή, ποτέ σιωπηλή αλλαγή.
--
-- Ο περιορισμός αφορά ΜΟΝΟ την κατάθεση πρότασης. Το φόρουμ, η διαβούλευση,
-- οι τροπολογίες και η ψήφος μένουν ανοιχτά σε κάθε μέλος — αλλιώς δεν θα
-- επρόκειτο για κοινότητα αλλά για ανακοινώσεις.

ALTER TABLE communities
  ADD COLUMN IF NOT EXISTS proposal_policy TEXT NOT NULL DEFAULT 'all_members';

COMMENT ON COLUMN communities.proposal_policy IS
  'Who may submit proposals: all_members | admins | founder. Autonomous communities are always all_members.';
